const origin = "http://127.0.0.1:3101";
function client() {
  let cookie = "";
  return async (path, method = "GET", data, expected = 200, extra = {}) => {
    const multipart = data instanceof FormData;
    const raw = data instanceof Uint8Array;
    const response = await fetch(origin + path, { signal: AbortSignal.timeout(20000), method, redirect: "manual", headers: { origin, ...(cookie ? {cookie} : {}), ...(data && !multipart && !raw ? {"content-type":"application/json"}: {}), ...extra }, body: data ? multipart || raw ? data : JSON.stringify(data) : undefined });
    const set = response.headers.getSetCookie().find(c => c.startsWith("kondo_session="));
    if(set) cookie = set.split(";")[0];
    assert.equal(response.status, expected, `${method} ${path}: ${response.status} ${expected !== response.status ? await response.text() : ""}`);
    if(response.headers.get("content-type")?.includes("application/json")) return response.json();
    const text = await response.text();
    assert.ok(!text.includes('Internal Server Error'), path);
    return text;
  };
}
