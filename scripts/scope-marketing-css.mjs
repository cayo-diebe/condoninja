// Isolate the reference Site's compiled utility stylesheet from the existing app.
// Run after replacing assets/marketing/reference.compiled.css with a newer export.
import fs from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const nextRequire = createRequire(require.resolve("next/package.json"));
const postcss = nextRequire("postcss");
const root = postcss.parse(fs.readFileSync("assets/marketing/reference.compiled.css", "utf8"));
root.walkAtRules("layer", rule => {
  if (rule.nodes) rule.replaceWith(...rule.nodes);
  else rule.remove();
});
root.walkRules(rule => {
  let ancestor = rule.parent;
  while (ancestor && ancestor.type !== "root") {
    if (ancestor.type === "rule" || /keyframes$/.test(ancestor.name ?? "")) return;
    ancestor = ancestor.parent;
  }
  rule.selectors = rule.selectors.map(selector => {
    if (/^(:root|:host|html|body)$/.test(selector)) return ".marketing-site";
    if (selector.startsWith(".js ")) return ".marketing-site " + selector.slice(4).replace(".reveal", ".reveal.is-ready");
    if (selector === "*") return ".marketing-site, .marketing-site *";
    return ".marketing-site " + selector;
  });
});
fs.writeFileSync("app/marketing.generated.css", "/* Generated by scripts/scope-marketing-css.mjs; do not edit. */\n" + root.toString());
